	srcIsKind = `
// isKind tells whether v, as encoding/json decodes it into any, is of one
// of the JSON kinds.
func isKind(v any, kinds ...string) bool {
	kind := "object"
	switch x := v.(type) {
	case nil:
		kind = "null"
	case bool:
		kind = "bool"
	case string:
		kind = "string"
	case []any:
		kind = "array"
	case float64:
		if x == math.Trunc(x) && slices.Contains(kinds, "int") {
			return true
		}
		kind = "number"
	}
	return slices.Contains(kinds, kind)
}`

