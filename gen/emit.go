package gen

import (
	"bytes"
	"errors"
	"fmt"
	goformat "go/format"
	"slices"
	"strconv"
	"strings"

	"cuelang.org/go/cue"
)

// Generate returns the Go source of the types that receive the
// configuration val describes, and what of the schema it cannot check.
func Generate(val cue.Value, opts Options) ([]byte, []string, error) {
	state := &generator{
		opts: opts, defs: map[string]*named{}, names: map[string]bool{},
		regexps: map[string]string{}, uses: map[string]bool{},
	}
	state.root = val
	root := state.typeOf(val, cue.Path{}, opts.Type)
	if root.kind != kStruct {
		return nil, state.warns, errNotStruct
	}
	root.named.name = opts.Type
	out := &emitter{g: state, needs: map[*named]bool{}}
	body := out.file(root.named)
	src, err := goformat.Source(body)
	if err != nil {
		return body, state.warns, fmt.Errorf("formatting the generated code: %w", err)
	}
	return src, state.warns, nil
}

// errNotStruct: the schema is no struct of fields, which Go types are.
var errNotStruct = errors.New("the schema must be a struct of fields")

type emitter struct {
	g     *generator
	needs map[*named]bool // types with generated checks
	buf   bytes.Buffer
}

func (e *emitter) pf(format string, args ...any) {
	fmt.Fprintf(&e.buf, format, args...)
	e.buf.WriteByte('\n')
}

func (e *emitter) file(root *named) []byte {
	for _, t := range e.g.types {
		e.needsCheck(t)
	}
	var body emitter
	body.g, body.needs = e.g, e.needs
	body.root(root)
	for _, t := range e.g.types {
		if t.isUnion {
			body.union(t)
		} else {
			body.structType(t)
		}
	}
	body.helpers()
	e.pf("// Code generated by cuegen from a CUE schema. DO NOT EDIT.")
	e.pf("")
	e.pf("package %s", e.g.opts.Package)
	e.pf("")
	e.pf("import (")
	for _, imp := range e.imports() {
		e.pf("%s", imp)
	}
	e.pf(")")
	e.buf.Write(body.buf.Bytes())
	return e.buf.Bytes()
}

func (e *emitter) imports() []string {
	out := []string{`"encoding/json"`, `"errors"`, `"fmt"`, `"reflect"`, `"slices"`, `"strings"`}
	for _, pkg := range []string{"math", "net/url", "regexp", "strconv", helperTime} {
		if e.needsImport(pkg) {
			out = append(out, strconv.Quote(pkg))
		}
	}
	slices.Sort(out)
	return append(out, "",
		`"github.com/go-playground/validator/v10"`,
		`"go.yaml.in/yaml/v3"`)
}

// needsImport: the generated code uses pkg, besides those it always does.
func (e *emitter) needsImport(pkg string) bool {
	switch pkg {
	case "regexp":
		return len(e.g.regexps) > 0
	case helperTime:
		return e.g.uses[helperTime] || e.g.uses[helperDuration]
	case "math":
		return e.g.uses[helperIsKind]
	case "net/url":
		return e.g.uses[helperURL]
	default:
		return e.g.uses[pkg]
	}
}

func (e *emitter) root(typ *named) {
	name := typ.name
	e.pf(`
// ParseJSON decodes a %[1]s from JSON, with the defaults of the schema
// for what it leaves out, and validates it.
func ParseJSON(data []byte) (*%[1]s, error) {
	var out %[1]s
	if err := json.Unmarshal(data, &out); err != nil {
		return nil, err
	}
	if err := out.Validate(); err != nil {
		return nil, err
	}
	return &out, nil
}

// ParseYAML decodes a %[1]s from YAML, as ParseJSON does.
func ParseYAML(data []byte) (*%[1]s, error) {
	doc := any(map[string]any{}) // an empty document is an empty struct
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, err
	}
	data, err := json.Marshal(doc)
	if err != nil {
		return nil, err
	}
	return ParseJSON(data)
}

// Validate checks x against the schema: validator's tags first, then
// what they cannot express.
func (x *%[1]s) Validate() error {
	var errs []error
	if err := validate.Struct(x); err != nil {
		errs = append(errs, err)
	}`, name)
	if e.needs[typ] {
		e.pf(`	x.check("", &errs)`)
	}
	e.pf("	return errors.Join(errs...)\n}")
}

func (e *emitter) comment(text, indent string) {
	if text == "" {
		return
	}
	for line := range strings.SplitSeq(text, "\n") {
		e.pf("%s// %s", indent, line)
	}
}

func (e *emitter) structType(typ *named) {
	e.pf("")
	e.comment(typ.doc, "")
	e.pf("type %s struct {", typ.name)
	for _, fld := range typ.fields {
		e.comment(fld.doc, "\t")
		if fld.computed {
			e.pf("\t// Computed by the schema.")
		}
		e.pf("\t%s %s `%s`", fld.goName, e.fieldType(fld), e.tag(fld))
	}
	e.pf("}")
	e.newFunc(typ)
	e.unmarshal(typ)
	if e.needs[typ] {
		e.checkFunc(typ)
	}
}

func (e *emitter) fieldType(f *field) string {
	if f.ptr {
		return "*" + e.g.goType(f.ref)
	}
	return e.g.goType(f.ref)
}

func (g *generator) goType(typ *ref) string {
	switch typ.kind {
	case kBool:
		return typeBool
	case kInt:
		return typeInt
	case kFloat:
		return "float64"
	case kString:
		return typeString
	case kBytes:
		return "[]byte"
	case kStruct, kUnion:
		return typ.named.name
	case kList:
		return "[]" + g.elemType(typ.elem)
	case kMap:
		return "map[string]" + g.elemType(typ.elem)
	default:
		return "any"
	}
}

// elemType is the Go type of the elements of a list or map: a pointer to
// a struct that may be null.
func (g *generator) elemType(elem *ref) string {
	if elemPtr(elem) {
		return "*" + g.goType(elem)
	}
	return g.goType(elem)
}

func elemPtr(elem *ref) bool { return elem.nullable && elem.kind == kStruct }

func (e *emitter) tag(fld *field) string {
	if fld.rest {
		out := `json:"-"`
		if rules := validateRules(fld, true); len(rules) > 1 {
			out += " validate:" + strconv.Quote(strings.Join(rules, ","))
		}
		return out
	}
	jsonTag := fld.json
	optional := isOptional(fld)
	if optional {
		jsonTag += ",omitempty"
	}
	out := "json:" + strconv.Quote(jsonTag)
	if rules := validateRules(fld, optional); len(rules) > 0 && !slices.Equal(rules, []string{omitEmpty}) {
		out += " validate:" + strconv.Quote(strings.Join(rules, ","))
	}
	return out
}

const omitEmpty = "omitempty"

// isOptional: the field may be left out (omitempty).
func isOptional(fld *field) bool {
	nilable := fld.ref.kind == kList || fld.ref.kind == kMap || fld.ref.kind == kUnion
	return fld.cond != nil || !fld.required && (fld.ptr || fld.def == "" && nilable)
}

// validateRules are the validator tags of a field.
func validateRules(fld *field, optional bool) []string {
	if fld.computed {
		return nil
	}
	var rules []string
	switch {
	case fld.required:
		rules = append(rules, "required")
	case optional:
		rules = append(rules, omitEmpty)
	}
	return append(rules, refTags(fld.ref)...)
}

// refTags are the validator tags of a value of type r, through the
// elements of lists and maps (dive).
func refTags(target *ref) []string {
	out := slices.Clone(target.tags)
	if target.kind != kList && target.kind != kMap {
		return out
	}
	inner := refTags(target.elem)
	var keys []string
	if target.key != nil {
		keys = target.key.tags
	}
	elem := target.elem.kind
	if len(inner) == 0 && len(keys) == 0 && elem != kStruct && elem != kUnion && elem != kList {
		return out
	}
	out = append(out, "dive")
	if len(keys) > 0 {
		out = append(append(append(out, "keys"), keys...), "endkeys")
	}
	return append(out, inner...)
}

func (e *emitter) newFunc(typ *named) {
	e.pf("\n// New%[1]s returns a %[1]s with the defaults of the schema.\nfunc New%[1]s() %[1]s {", typ.name)
	inits := initsOf(typ)
	ret := "return"
	if hasCondDefaults(typ) {
		ret = "out :="
	}
	if len(inits) == 0 {
		e.pf("\t%s %s{}", ret, typ.name)
	} else {
		e.pf("\t%s %s{", ret, typ.name)
		for _, init := range inits {
			e.pf("\t\t%s", init)
		}
		e.pf("\t}")
	}
	if hasCondDefaults(typ) {
		e.pf("\tout.defaults()\n\treturn out")
	}
	e.pf("}")
	e.defaultsFunc(typ)
}

// initsOf are the fields of a composite literal of typ with its defaults.
func initsOf(typ *named) []string {
	var inits []string
	for _, fld := range typ.fields {
		switch {
		case fld.def == "0" || fld.def == litFalse || fld.def == `""`: // the zero value
		case fld.def != "":
			inits = append(inits, fmt.Sprintf("%s: %s,", fld.goName, fld.def))
		case !fld.ptr && fld.ref.kind == kStruct:
			inits = append(inits, fmt.Sprintf("%s: New%s(),", fld.goName, fld.ref.named.name))
		}
	}
	return inits
}

func hasCondDefaults(typ *named) bool {
	return slices.ContainsFunc(typ.fields, func(fld *field) bool { return fld.cond != nil && len(fld.cond.defaults) > 0 })
}

// defaultsFunc sets the defaults of the fields that exist only for some
// values of another: they depend on what was decoded.
func (e *emitter) defaultsFunc(typ *named) {
	if !hasCondDefaults(typ) {
		return
	}
	e.pf("\nfunc (x *%s) defaults() {", typ.name)
	for _, fld := range typ.fields {
		if fld.cond == nil {
			continue
		}
		for _, def := range fld.cond.defaults {
			expr := def.expr
			if fld.ptr {
				e.g.uses[helperPtr] = true
				expr = "ptr(" + expr + ")"
			}
			e.pf("\tif x.%s == nil && %s {\n\t\tx.%s = %s\n\t}",
				fld.goName, condExpr(fld.cond.ctrl, def.values), fld.goName, expr)
		}
	}
	e.pf("}")
}

// condExpr is true when the field ctrl has one of values.
func condExpr(ctrl *field, values []string) string {
	value := "x." + ctrl.goName
	if ctrl.ptr {
		value = "*" + value
	}
	parts := make([]string, len(values))
	for idx, lit := range values {
		switch lit {
		case litTrue:
			parts[idx] = value
		case litFalse:
			parts[idx] = "!" + value
		default:
			parts[idx] = value + " == " + lit
		}
	}
	out := strings.Join(parts, " || ")
	if len(parts) > 1 {
		out = "(" + out + ")"
	}
	if ctrl.ptr {
		out = "x." + ctrl.goName + " != nil && " + out
	}
	return out
}

// unmarshal decodes over the defaults, rejects unknown keys of a closed
// struct and picks the variant of each union.
func (e *emitter) unmarshal(typ *named) {
	var unions []*field
	for _, fld := range typ.fields {
		if decoder(fld.ref) != "" {
			unions = append(unions, fld)
		}
	}
	e.pf(`
// UnmarshalJSON decodes data over the defaults of the schema.
func (x *%[1]s) UnmarshalJSON(data []byte) error {
	if err := checkKeys(data, %[2]t, map[string]string{%[3]s}); err != nil {
		return err
	}
	type plain %[1]s
	*x = New%[1]s()
	aux := struct {
		*plain`, typ.name, typ.closed && restOf(typ) == nil, keyRules(typ))
	for _, fld := range unions {
		e.pf("\t\t%s %s `json:%q`", fld.goName, rawType(fld.ref), fld.json)
	}
	e.pf("\t}{plain: (*plain)(x)}")
	for _, fld := range typ.fields {
		if fld.cond != nil && len(fld.cond.defaults) > 0 {
			e.pf("\tx.%s = nil // set by defaults, from what is decoded", fld.goName)
		}
	}
	e.pf(`	if err := json.Unmarshal(data, &aux); err != nil {
		return err
	}`)
	for _, fld := range unions {
		e.unionDecode(fld)
	}
	e.restDecode(typ)
	if hasCondDefaults(typ) {
		e.pf("\tx.defaults()")
	}
	e.pf("\treturn nil\n}")
	e.restEncode(typ)
}

// unionDecode picks the variant of a union field, or of the elements of
// a list or map of them, from the raw value decoded into aux.
func (e *emitter) unionDecode(fld *field) {
	notNull := ""
	if fld.ref.kind == kUnion {
		notNull = fmt.Sprintf(` && string(aux.%s) != "null"`, fld.goName)
	}
	e.pf("\tif aux.%[1]s != nil%[3]s {\n\t\tvar err error\n"+
		"\t\tif x.%[1]s, err = %[2]s; err != nil {\n\t\t\treturn err\n\t\t}\n\t}",
		fld.goName, fmt.Sprintf(decoder(fld.ref), "aux."+fld.goName), notNull)
}

// restDecode decodes the keys typ does not declare into its rest field.
func (e *emitter) restDecode(typ *named) {
	if rest := restOf(typ); rest != nil {
		e.g.uses[helperRest] = true
		e.pf("\trest, err := restOf[%s](data, %s)\n\tif err != nil {\n\t\treturn err\n\t}\n\tx.%s = rest",
			e.g.elemType(rest.ref.elem), declaredKeys(typ), rest.goName)
	}
}

// restEncode writes them back.
func (e *emitter) restEncode(typ *named) {
	if rest := restOf(typ); rest != nil {
		e.pf("\n// MarshalJSON writes x with the fields %[2]s holds.\nfunc (x %[1]s) MarshalJSON() ([]byte, error) {"+
			"\n\ttype plain %[1]s\n\treturn withRest(plain(x), x.%[2]s)\n}", typ.name, rest.goName)
	}
}

// restOf is the field of typ that keeps the keys it does not declare.
func restOf(typ *named) *field {
	for _, fld := range typ.fields {
		if fld.rest {
			return fld
		}
	}
	return nil
}

func declaredKeys(typ *named) string {
	keys := make([]string, 0, len(typ.fields))
	for _, fld := range typ.fields {
		if !fld.rest {
			keys = append(keys, strconv.Quote(fld.json))
		}
	}
	return strings.Join(keys, ", ")
}

// keyRules says, per key of t, where null is allowed: "null" in its
// value, "elems" for none in the elements of its list or map, "" none.
func keyRules(typ *named) string {
	rules := make([]string, 0, len(typ.fields))
	for _, fld := range typ.fields {
		if fld.rest {
			continue
		}
		rule := ""
		switch {
		case fld.ref.nullable || fld.computed:
			rule = jsonNull
		case (fld.ref.kind == kList || fld.ref.kind == kMap) && (isScalar(fld.ref.elem.kind) || fld.ref.elem.kind == kAny) &&
			!fld.ref.elem.nullable:
			rule = "elems"
		}
		rules = append(rules, fmt.Sprintf("%q: %q", fld.json, rule))
	}
	return strings.Join(rules, ", ")
}

func isScalar(k kind) bool { return k > kAny && k < kStruct }

// decoder is the call that decodes a raw value of type r holding unions,
// "" if it has none (decoding is then plain).
func decoder(target *ref) string {
	switch {
	case target.kind == kUnion:
		return "decode" + target.named.name + "(%s)"
	case (target.kind == kList || target.kind == kMap) && target.elem.kind == kUnion:
		container := map[kind]string{kList: "List", kMap: "Map"}[target.kind]
		return "decode" + container + "(%s, decode" + target.elem.named.name + ")"
	}
	return ""
}

func rawType(typ *ref) string {
	switch typ.kind {
	case kList:
		return "[]json.RawMessage"
	case kMap:
		return "map[string]json.RawMessage"
	default:
		return "json.RawMessage"
	}
}

func (e *emitter) union(typ *named) {
	e.g.uses["fmt"] = true
	e.pf("")
	e.comment(typ.doc, "")
	names := make([]string, len(typ.variants))
	for idx, variant := range typ.variants {
		names[idx] = "*" + variant.name
	}
	e.pf("//\n// It is one of %s.\ntype %s interface{ is%s() }\n", strings.Join(names, ", "), typ.name, typ.name)
	for _, variant := range typ.variants {
		e.pf("func (*%s) is%s() {}", variant.name, typ.name)
	}
	if typ.discr == "" {
		e.byTrying(typ)
		return
	}
	e.pf(`
func decode%[1]s(data []byte) (%[1]s, error) {
	var keys map[string]json.RawMessage
	if err := json.Unmarshal(data, &keys); err != nil {
		return nil, err
	}
	var out %[1]s`, typ.name)
	e.byDiscriminator(typ)
	e.pf("\treturn out, json.Unmarshal(data, out)\n}")
}

func (e *emitter) byDiscriminator(typ *named) {
	e.pf("\tswitch string(keys[%q]) {", typ.discr)
	for idx, variant := range typ.variants {
		cases := strconv.Quote(typ.tells[idx])
		if idx == typ.def {
			cases += `, ""`
		}
		e.pf("\tcase %s:\n\t\tout = new(%s)", cases, variant.name)
	}
	e.pf("\tdefault:\n\t\treturn nil, fmt.Errorf(\"%s: %%s is none of the variants\", keys[%q])\n\t}",
		typ.discr, typ.discr)
}

// byTrying decodes a union with no discriminator as CUE resolves the
// disjunction: the variant the value fits, the default if several do.
func (e *emitter) byTrying(typ *named) {
	e.g.uses[helperPick], e.g.uses[helperChecker] = true, true
	news := make([]string, len(typ.variants))
	for idx, variant := range typ.variants {
		news[idx] = "new(" + variant.name + ")"
	}
	e.pf("\nfunc decode%[1]s(data []byte) (%[1]s, error) {\n\treturn pickVariant[%[1]s](data, %[2]d, %[3]s)\n}",
		typ.name, typ.def, strings.Join(news, ", "))
}

// needsCheck: values of typ have checks that are generated code.
func (e *emitter) needsCheck(typ *named) bool {
	if done, ok := e.needs[typ]; ok {
		return done
	}
	e.needs[typ] = false // a cycle adds nothing
	out := false
	for _, fld := range typ.fields {
		conditional := fld.cond != nil && len(fld.cond.required)+len(fld.cond.forbidden) > 0
		out = out || !fld.computed && e.refNeeds(fld.ref) || conditional
	}
	out = out || len(typ.oneOfs) > 0
	for _, variant := range typ.variants {
		out = e.needsCheck(variant) || out
	}
	e.needs[typ] = out
	return out
}

func (e *emitter) refNeeds(target *ref) bool {
	switch {
	case len(target.checks) > 0 || target.key != nil && len(target.key.checks) > 0:
		return true
	case target.kind == kStruct || target.kind == kUnion:
		return e.needsCheck(target.named)
	case target.elem != nil:
		return e.refNeeds(target.elem)
	}
	return false
}

func (e *emitter) checkFunc(typ *named) {
	e.pf("\nfunc (x *%s) check(path string, errs *[]error) {", typ.name)
	for _, rule := range typ.oneOfs {
		e.oneOfCheck(typ, rule)
	}
	for _, fld := range typ.fields {
		e.condChecks(fld)
		switch {
		case fld.computed || !e.refNeeds(fld.ref):
		case fld.rest: // its keys are fields of the struct
			e.checkValue("x."+fld.goName, "path", fld.ref, false, 1)
		default:
			e.checkValue("x."+fld.goName, fmt.Sprintf("join(path, %q)", fld.json), fld.ref, fld.ptr, 1)
		}
	}
	e.pf("}")
}

// condChecks checks that a field of an if is given or left out as the
// field it depends on requires.
func (e *emitter) condChecks(fld *field) {
	if fld.cond == nil {
		return
	}
	if len(fld.cond.required) > 0 {
		e.failIf(fmt.Sprintf("x.%s == nil && %s", fld.goName, condExpr(fld.cond.ctrl, fld.cond.required)),
			fmt.Sprintf("join(path, %q)", fld.json), "required")
	}
	if len(fld.cond.forbidden) > 0 {
		e.failIf(fmt.Sprintf("x.%s != nil && %s", fld.goName, condExpr(fld.cond.ctrl, fld.cond.forbidden)),
			fmt.Sprintf("join(path, %q)", fld.json), "not allowed")
	}
}

// checkValue emits the checks of the value expr, of type r, at the path
// the Go expression path gives.
func (e *emitter) checkValue(expr, path string, target *ref, ptr bool, depth int) {
	if ptr && target.kind != kStruct {
		e.pf("if %s != nil {", expr)
		defer e.pf("}")
		expr = "(*" + expr + ")"
	}
	if target.kind == kAny && len(target.checks) > 0 {
		e.pf("if %s != nil {", expr)
		defer e.pf("}")
	}
	for _, valueCheck := range target.checks {
		e.failIf(fmt.Sprintf(valueCheck.cond, expr), path, valueCheck.msg)
	}
	switch target.kind {
	case kStruct, kUnion:
		e.checkNamed(expr, path, target.kind, ptr)
	case kList:
		e.checkList(expr, path, target, depth)
	case kMap:
		e.checkMap(expr, path, target, depth)
	default:
	}
}

// checkNamed calls the checks of a struct, or of the variant of a union.
func (e *emitter) checkNamed(expr, path string, of kind, ptr bool) {
	switch {
	case of == kUnion:
		e.g.uses[helperChecker] = true
		e.pf("if c, ok := %s.(checker); ok {\nc.check(%s, errs)\n}", expr, path)
	case ptr:
		e.pf("if %s != nil {\n%s.check(%s, errs)\n}", expr, expr, path)
	default:
		e.pf("%s.check(%s, errs)", expr, path)
	}
}

func (e *emitter) checkList(expr, path string, list *ref, depth int) {
	e.g.uses["strconv"] = true
	idx, elem := fmt.Sprintf("i%d", depth), fmt.Sprintf("v%d", depth)
	e.pf("for %s, %s := range %s {", idx, elem, expr)
	e.checkValue(elem, fmt.Sprintf(`%s+"["+strconv.Itoa(%s)+"]"`, path, idx), list.elem, elemPtr(list.elem), depth+1)
	e.pf("}")
}

func (e *emitter) checkMap(expr, path string, dict *ref, depth int) {
	key, elem := fmt.Sprintf("k%d", depth), fmt.Sprintf("v%d", depth)
	if e.refNeeds(dict.elem) {
		e.pf("for %s, %s := range %s {", key, elem, expr)
	} else {
		elem = "_"
		e.pf("for %s := range %s {", key, expr)
	}
	if dict.key != nil {
		for _, keyCheck := range dict.key.checks {
			e.failIf(fmt.Sprintf(keyCheck.cond, key), fmt.Sprintf("join(%s, %s)", path, key), "key "+keyCheck.msg)
		}
	}
	if elem != "_" {
		e.checkValue(elem, fmt.Sprintf("join(%s, %s)", path, key), dict.elem, elemPtr(dict.elem), depth+1)
	}
	e.pf("}")
}

// oneOfCheck counts the alternatives whose keys are all given.
func (e *emitter) oneOfCheck(typ *named, rule oneOf) {
	e.g.uses[helperCount] = true
	alts := make([]string, len(rule.keys))
	names := make([]string, len(rule.keys))
	for idx, keys := range rule.keys {
		given := make([]string, len(keys))
		for k, key := range keys {
			fld := typ.fields[slices.IndexFunc(typ.fields, func(fld *field) bool { return fld.json == key })]
			given[k] = "true"
			if fld.ptr || fld.def == "" && fld.ref.kind >= kUnion || fld.ref.kind == kAny {
				given[k] = "x." + fld.goName + " != nil"
			}
		}
		alts[idx], names[idx] = strings.Join(given, " && "), strings.Join(keys, " and ")
	}
	op, msg := "!= 1", "exactly one of "
	if !rule.exact {
		op, msg = "== 0", "at least one of "
	}
	e.failIf(fmt.Sprintf("count(%s) %s", strings.Join(alts, ", "), op), "path",
		msg+strings.Join(names, " | ")+" must be given")
}

func (e *emitter) failIf(cond, path, msg string) {
	e.pf("if %s {\n*errs = append(*errs, errors.New(%s+%q))\n}", cond, path, ": "+msg)
}

func (e *emitter) helpers() {
	e.pf(`
var validate = newValidator()

// newValidator names fields in errors by their JSON key.
func newValidator() *validator.Validate {
	out := validator.New()
	out.RegisterTagNameFunc(func(f reflect.StructField) string {
		name, _, _ := strings.Cut(f.Tag.Get("json"), ",")
		return name
	})
	return out
}

func join(path, name string) string {
	if path == "" {
		return name
	}
	return path + "." + name
}`)
	patterns := make([]string, 0, len(e.g.regexps))
	for pattern := range e.g.regexps {
		patterns = append(patterns, pattern)
	}
	slices.SortFunc(patterns, func(a, b string) int { return strings.Compare(e.g.regexps[a], e.g.regexps[b]) })
	for _, pattern := range patterns {
		e.pf("\nvar %s = regexp.MustCompile(%s)", e.g.regexps[pattern], strconv.Quote(pattern))
	}
	for _, name := range []string{helperPtr, helperFromJSON, helperCheckKeys, helperPick, helperChecker,
		helperDuration, helperTime, helperUnionList, helperIsKind, helperCount, helperURL, helperRest} {
		if e.g.uses[name] || name == helperCheckKeys || name == helperUnionList {
			e.pf("%s", helperSource(name))
		}
	}
}

