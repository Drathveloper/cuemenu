	srcCheckKeys = `
// checkKeys checks the keys of a struct in data: none unknown if it is
// closed, and null only where the schema allows it. rules says, per key,
// "null" if its value may be null, "elems" if the elements of its list or
// map may not.
func checkKeys(data []byte, closed bool, rules map[string]string) error {
	if string(data) == "null" {
		return errors.New("null is not allowed")
	}
	var got map[string]json.RawMessage
	if err := json.Unmarshal(data, &got); err != nil {
		return err
	}
	for key, raw := range got {
		rule, known := rules[key]
		switch {
		case !known && closed:
			return fmt.Errorf("field %q not allowed", key)
		case !known:
		case string(raw) == "null" && rule != "null":
			return fmt.Errorf("%s: null is not allowed", key)
		case rule == "elems" && hasNull(raw):
			return fmt.Errorf("%s: null elements are not allowed", key)
		}
	}
	return nil
}

func hasNull(raw json.RawMessage) bool {
	var list []json.RawMessage
	if json.Unmarshal(raw, &list) == nil {
		return slices.ContainsFunc(list, func(elem json.RawMessage) bool { return string(elem) == "null" })
	}
	var obj map[string]json.RawMessage
	if json.Unmarshal(raw, &obj) == nil {
		for _, elem := range obj {
			if string(elem) == "null" {
				return true
			}
		}
	}
	return false
}`

	srcPick = `
// pickVariant decodes data as the variant it fits, validated: the only
// one, else the default (def, -1 if none), else the first.
func pickVariant[T any](data []byte, def int, variants ...T) (T, error) {
	var fits []int
	var first error
	for idx, variant := range variants {
		if err := attempt(data, variant); err == nil {
			fits = append(fits, idx)
		} else if first == nil {
			first = err
		}
	}
	var none T
	switch {
	case len(fits) == 0:
		return none, fmt.Errorf("none of the variants fits: %w", first)
	case slices.Contains(fits, def):
		return variants[def], nil
	}
	return variants[fits[0]], nil
}

func attempt(data []byte, target any) error {
	if err := json.Unmarshal(data, target); err != nil {
		return err
	}
	var errs []error
	if err := validate.Struct(target); err != nil {
		errs = append(errs, err)
	}
	if c, ok := target.(checker); ok {
		c.check("", &errs)
	}
	return errors.Join(errs...)
}`

	srcRest = `
// restOf decodes the keys of data that are not declared.
func restOf[T any](data []byte, declared ...string) (map[string]T, error) {
	var all map[string]json.RawMessage
	if err := json.Unmarshal(data, &all); err != nil {
		return nil, err
	}
	var out map[string]T
	for key, raw := range all {
		if slices.Contains(declared, key) {
			continue
		}
		var val T
		if err := json.Unmarshal(raw, &val); err != nil {
			return nil, fmt.Errorf("%s: %w", key, err)
		}
		if out == nil {
			out = map[string]T{}
		}
		out[key] = val
	}
	return out, nil
}

// withRest writes v with the keys of rest added.
func withRest[T any](v any, rest map[string]T) ([]byte, error) {
	data, err := json.Marshal(v)
	if err != nil || len(rest) == 0 {
		return data, err
	}
	var all map[string]json.RawMessage
	if err := json.Unmarshal(data, &all); err != nil {
		return nil, err
	}
	for key, val := range rest {
		if all[key], err = json.Marshal(val); err != nil {
			return nil, err
		}
	}
	return json.Marshal(all)
}`

