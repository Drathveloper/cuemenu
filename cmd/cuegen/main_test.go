package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const (
	example   = "../../examples/webapp"
	usageHead = "usage: cuegen"
)

func TestRun(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name   string
		stdout string // a part of it
		stderr string // a part of it
		args   []string
		code   int
	}{
		{name: "help", args: []string{"-h"}, stderr: usageHead, code: exitOK},
		{name: "version", args: []string{"-version"}, stdout: "cuegen dev", code: exitOK},
		{name: "bad flag", args: []string{"-nope"}, stderr: usageHead, code: exitUsage},
		{name: "two dirs", args: []string{"a", "b"}, stderr: usageHead, code: exitUsage},
		{name: "no package", args: []string{t.TempDir()}, stderr: "cuegen:", code: exitFail},
		{name: "no path", args: []string{"-e", "#Nope", example}, stderr: "not in the package", code: exitFail},
		{
			name: "stdout", args: []string{"-pkg", "settings", "-type", "Settings", example},
			stdout: "package settings", stderr: "warning: server.root_url", code: exitOK,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			var stdout, stderr bytes.Buffer
			if code := run(tt.args, &stdout, &stderr); code != tt.code {
				t.Fatalf("exit code %d, want %d; stderr:\n%s", code, tt.code, stderr.String())
			}
			if !strings.Contains(stdout.String(), tt.stdout) || !strings.Contains(stderr.String(), tt.stderr) {
				t.Fatalf("stdout:\n%.300s\nstderr:\n%s", stdout.String(), stderr.String())
			}
		})
	}
}

func TestRunWritesFile(t *testing.T) {
	t.Parallel()
	out := filepath.Join(t.TempDir(), "config_gen.go")
	var stdout, stderr bytes.Buffer
	if code := run([]string{"-o", out, example}, &stdout, &stderr); code != exitOK {
		t.Fatalf("exit code %d: %s", code, stderr.String())
	}
	data, err := os.ReadFile(out) //nolint:gosec // a file of the test
	if err != nil || !bytes.HasPrefix(data, []byte("// Code generated by cuegen")) || stdout.Len() > 0 {
		t.Fatalf("%v, wrote %.80q, stdout %q", err, data, stdout.String())
	}
}
