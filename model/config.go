// Errors returned by Config. Their messages are shown to the user.
var (
	ErrUndeclared  = errors.New("field not declared in the schema")
	ErrRejected    = errors.New("value rejected")
	ErrInvalidExpr = errors.New("invalid CUE expression")
	ErrIncomplete  = errors.New("incomplete configuration")
	ErrFormat      = errors.New("unsupported format (json, yaml)")
	ErrKeyExists   = errors.New("key already exists")
	ErrKeyPattern  = errors.New("key matches no pattern")
	ErrNotVariant  = errors.New("not a variant")
)

const (
	header     = "// Generated by cuemenu: contains only the changed values.\n\n"
	configMode = 0o600 // the saved edits may hold secrets
	maxCauses  = 3     // causes of a rejection shown to the user
)

// Config is a schema plus the values the user changed (the edits).
// Like the kernel's .config, only edits are saved; everything else comes
// from the schema, so schema defaults keep flowing in.
type Config struct {
	ctx    *cue.Context
	edits  map[string]edit // keyed by path string
	schema cue.Value
}

type edit struct {
	val  cue.Value
	path cue.Path
}

// New returns a configuration of schema with no edits.
func New(schema cue.Value) *Config {
	return &Config{ctx: cuecontext.New(), edits: map[string]edit{}, schema: schema}
}

// Value is the schema unified with every edit.
func (c *Config) Value() cue.Value { return c.apply(func(cue.Path) bool { return true }) }

// Set changes the field at path. x is a Go value (string, bool, int,
// float, slices, maps) or a cue.Value compiled from an expression. The
// change is rejected if it introduces new evaluation errors. Edits that
// stop making sense (fields of a variant no longer chosen) are dropped
// first. A struct replaces everything below path and is stored as its
// leaves, so edits never nest and any part can be unset on its own.
func (c *Config) Set(path cue.Path, x any) error {
	val, ok := x.(cue.Value)
	if !ok {
		val = c.ctx.Encode(x)
	}
	if err := val.Err(); err != nil {
		return fmt.Errorf("%w: %w", ErrInvalidExpr, err)
	}
	before := errorSet(c.Value())
	saved := maps.Clone(c.edits)
	c.unsetBelow(path)
	news := leaves(val, path)
	keys := make([]string, 0, len(news))
	for _, ed := range news {
		c.edits[ed.path.String()] = ed
		keys = append(keys, ed.path.String())
	}
	c.prune(keys...)
	for _, ed := range news {
		if _, _, found := find(c.without(ed.path), ed.path); !found {
			c.edits = saved
			return fmt.Errorf("%s: %w", ed.path, ErrUndeclared)
		}
	}
	if causes := newErrors(c.Value(), before); len(causes) > 0 {
		c.edits = saved
		return fmt.Errorf("%w:\n%s", ErrRejected, strings.Join(causes, "\n"))
	}
	return nil
}

// SetExpr sets the field at path to a CUE expression typed by the user:
// `8080`, `"x"`, `["a", "b"]`, `null`, `>=3`... It cannot reference other
// fields of the configuration.
func (c *Config) SetExpr(path cue.Path, expr string) error {
	val := c.ctx.CompileString(expr)
	if err := val.Err(); err != nil {
		return fmt.Errorf("%w: %w", ErrInvalidExpr, err)
	}
	return c.Set(path, val)
}

// Unset returns the field at path, and everything below it, to its schema
// value. Removing edits never adds a conflict, so it needs no validation.
func (c *Config) Unset(path cue.Path) {
	c.unsetBelow(path)
	c.prune()
}

// Tree is the menu tree of the current config.
func (c *Config) Tree() []*Node {
	full := c.Value()
	errs := map[string][]string{}
	for _, cerr := range cueerrors.Errors(full.Validate()) {
		labels := cerr.Path()
		sels := make([]cue.Selector, 0, len(labels))
		for _, label := range labels {
			sels = append(sels, cue.Str(label))
		}
		key := cue.MakePath(sels...).String()
		errs[key] = append(errs[key], cerr.Error())
	}
	return c.build(full, cue.Path{}, errs)
}

// Load reads edits saved by Save. A missing file means no edits. Edits
// that no longer fit the schema are dropped and returned.
func (c *Config) Load(path string) ([]string, error) {
	data, err := os.ReadFile(path) //nolint:gosec // the user chooses which file to load
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("reading %s: %w", path, err)
	}
	saved := c.ctx.CompileBytes(data, cue.Filename(path))
	if cerr := saved.Err(); cerr != nil {
		return nil, fmt.Errorf("%s: %w", path, cerr)
	}
	iter, ierr := saved.Fields()
	for ierr == nil && iter.Next() {
		for _, ed := range leaves(iter.Value(), child(cue.Path{}, iter.Selector())) {
			c.edits[ed.path.String()] = ed
		}
	}
	return c.prune(), nil
}

// Save writes the edits as CUE, readable only by the owner.
func (c *Config) Save(path string) error {
	saved := c.ctx.CompileString("{}")
	for _, key := range c.keys() {
		saved = saved.FillPath(c.edits[key].path, c.edits[key].val)
	}
	file := &ast.File{}
	if lit, ok := saved.Syntax().(*ast.StructLit); ok {
		file.Decls = lit.Elts
	}
	data, err := cueformat.Node(file)
	if err != nil {
		return fmt.Errorf("formatting the configuration: %w", err)
	}
	return WriteFile(path, append([]byte(header), data...), configMode)
}

// Check reports what keeps the configuration from being exported:
// required fields without value, values not concrete yet and conflicts,
// with the position in the schema of each.
func (c *Config) Check() error {
	if err := c.Value().Validate(cue.Concrete(true)); err != nil {
		return fmt.Errorf("%w:\n%s", ErrIncomplete, cueerrors.Details(err, nil))
	}
	return nil
}

// Export renders the final configuration as "json" or "yaml". It fails
// while any field is incomplete, e.g. a required field without value.
func (c *Config) Export(encoding string) ([]byte, error) {
	if err := c.Check(); err != nil {
		return nil, err
	}
	val := c.Value()
	switch encoding {
	case "json":
		data, err := json.MarshalIndent(val, "", "  ")
		if err != nil {
			return nil, fmt.Errorf("encoding json: %w", err)
		}
		return append(data, '\n'), nil
	case "yaml":
		data, err := yaml.Encode(val)
		if err != nil {
			return nil, fmt.Errorf("encoding yaml: %w", err)
		}
		return data, nil
	}
	return nil, fmt.Errorf("%w: %q", ErrFormat, encoding)
}

func (c *Config) apply(keep func(cue.Path) bool) cue.Value {
	val := c.schema
	for _, key := range c.keys() {
		if ed := c.edits[key]; keep(ed.path) {
			val = val.FillPath(ed.path, ed.val)
		}
	}
	return val
}

// without is the config minus the edits that touch path (at, below or
// above it): what the field looks like if the user had not touched it.
func (c *Config) without(path cue.Path) cue.Value {
	return c.apply(func(other cue.Path) bool { return !touches(other, path) })
}

func (c *Config) edited(path cue.Path) bool {
	for _, ed := range c.edits {
		if touches(ed.path, path) {
			return true
		}
	}
	return false
}

func (c *Config) keys() []string {
	return slices.Sorted(maps.Keys(c.edits))
}

func (c *Config) unsetBelow(path cue.Path) {
	for key, ed := range c.edits {
		if under(ed.path, path) {
			delete(c.edits, key)
		}
	}
}

// prune drops edits whose field no longer exists, e.g. a field inside an
// `if` whose condition changed, or a field of a variant no longer chosen.
// Kconfig drops symbols that become invisible in the same way.
// The protected edits (the ones just made) win: when two edits exclude
// each other, e.g. fields of two variants, the older one is dropped.
func (c *Config) prune(protect ...string) []string {
	var dropped []string
	for changed := true; changed; {
		changed = false
		for key, ed := range c.edits {
			if slices.Contains(protect, key) {
				continue
			}
			if _, _, found := find(c.without(ed.path), ed.path); !found {
				delete(c.edits, key)
				dropped = append(dropped, key)
				changed = true
			}
		}
	}
	slices.Sort(dropped)
	return dropped
}

func (c *Config) build(val cue.Value, parent cue.Path, errs map[string][]string) []*Node {
	iter, err := val.Fields(cue.Optional(true))
	if err != nil {
		return nil
	}
	var nodes []*Node
	for iter.Next() {
		nodes = append(nodes, c.buildNode(val, iter.Selector(), iter.Value(), parent, errs))
	}
	return nodes
}

func (c *Config) buildNode(
	owner cue.Value, sel cue.Selector, fld cue.Value, parent cue.Path, errs map[string][]string,
) *Node {
	path := child(parent, sel)
	node := &Node{Path: path, Label: sel.Unquoted(), Doc: doc(fld), Errors: errs[path.String()]}
	_, node.Set = c.edits[path.String()]
	node.Secret = secret(fld) || secret(owner.LookupPath(cue.MakePath(declSel(sel))))
	// The widget comes from the field as declared, ignoring the user's
	// own edits; the value shown comes from the edited config.
	decl := fld
	if c.edited(path) {
		decl, sel, _ = find(c.without(path), path)
	}
	node.Required = sel.ConstraintType() == cue.RequiredConstraint
	node.Optional = sel.ConstraintType() == cue.OptionalConstraint
	classify(node, decl)
	c.fill(node, fld, decl, errs)
	return node
}

// fill sets the value and children of node from fld, its edited value.
func (c *Config) fill(node *Node, fld, decl cue.Value, errs map[string][]string) {
	switch node.Widget {
	case Menu, Map:
		node.Children = c.build(fld, node.Path, errs)
	case List:
		node.Value = leafValue(fld)
		node.Children, node.Elem = listItems(fld, decl, node.Path)
	case Variant:
		c.fillVariant(node, fld, decl, errs)
	case ReadOnly, Toggle, Choice, Number, Text, Expr:
		node.Value = leafValue(fld)
	}
}

func (c *Config) fillVariant(node *Node, fld, decl cue.Value, errs map[string][]string) {
	chosen := fld
	if def, ok := fld.Default(); ok {
		chosen = def
	}
	node.Children = c.build(chosen, node.Path, errs)
	if node.discr.String() != "" {
		// The discriminator is where the variant is chosen.
		node.Value, _ = chosen.LookupPath(node.discr).String()
		for _, sub := range node.Children {
			if sub.Label == node.discr.String() {
				sub.Widget, sub.Options = Choice, quoteAll(node.Options)
			}
		}
		return
	}
	// No discriminator: a synthetic first entry chooses the variant.
	_, alts := decl.Expr()
	if idx := chosenVariant(chosen, alts); idx >= 0 {
		node.Value = node.Options[idx]
	}
	chooser := &Node{
		Path: node.Path, Label: "variant", Widget: Choice, Chooser: true,
		Options: node.Options, Value: node.Value,
		Doc: "Choose the variant. If it is told apart by a field, you will be asked for its value.",
	}
	node.Children = append([]*Node{chooser}, node.Children...)
}

// WriteFile replaces path atomically: the data is written to a temporary
// file created 0600 and renamed over path. A secret is never readable
// through the permissions of the file being replaced, and readers never
// see half a file.
func WriteFile(path string, data []byte, mode os.FileMode) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".cuemenu-*")
	if err != nil {
		return fmt.Errorf("creating a temporary file: %w", err)
	}
	defer func() { _ = os.Remove(tmp.Name()) }() // fails harmlessly after the rename
	_, err = tmp.Write(data)
	if err == nil {
		err = tmp.Chmod(mode)
	}
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Rename(tmp.Name(), path)
	}
	if err != nil {
		return fmt.Errorf("writing %s: %w", path, err)
	}
	return nil
}

// leaves splits a struct value into one edit per leaf field. An empty
// struct is kept as an edit: it creates a map entry with no fields yet.
func leaves(val cue.Value, path cue.Path) []edit {
	if val.IncompleteKind() != cue.StructKind {
		return []edit{{val: val, path: path}}
	}
	var out []edit
	iter, err := val.Fields()
	for err == nil && iter.Next() {
		out = append(out, leaves(iter.Value(), child(path, iter.Selector()))...)
	}
	if len(out) == 0 {
		return []edit{{val: val, path: path}}
	}
	return out
}

// newErrors returns the errors of val not in before, keeping the causes:
// CUE reports a failed disjunction as a header ("N errors in empty
// disjunction:") followed by one error per alternative.
func newErrors(val cue.Value, before map[string]bool) []string {
	var all, causes []string
	for _, cerr := range cueerrors.Errors(val.Validate()) {
		if msg := cerr.Error(); !before[msg] {
			all = append(all, msg)
			if !strings.HasSuffix(msg, "empty disjunction:") {
				causes = append(causes, msg)
			}
		}
	}
	if len(causes) == 0 {
		causes = all
	}
	return causes[:min(maxCauses, len(causes))]
}

func errorSet(val cue.Value) map[string]bool {
	set := map[string]bool{}
	for _, cerr := range cueerrors.Errors(val.Validate()) {
		set[cerr.Error()] = true
	}
	return set
}

// secret reports @menu(secret). The field iterator sometimes drops
// attributes that LookupPath keeps, so callers check both.
func secret(val cue.Value) bool {
	attr := val.Attribute("menu")
	ok, _ := attr.Flag(0, "secret")
	return ok
}

// declSel rebuilds sel as a plain string selector keeping its ! or ?
// marker: selectors from the field iterator do not always work with
// LookupPath.
func declSel(sel cue.Selector) cue.Selector {
	plain := cue.Str(sel.Unquoted())
	if sel.ConstraintType() == cue.OptionalConstraint {
		return plain.Optional()
	}
	if sel.ConstraintType() == cue.RequiredConstraint {
		return plain.Required()
	}
	return plain
}

func quoteAll(names []string) []string {
	quoted := make([]string, len(names))
	for idx, name := range names {
		quoted[idx] = literal.String.Quote(name)
	}
	return quoted
}
